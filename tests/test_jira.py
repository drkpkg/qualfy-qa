import json

import httpx
import pytest

from qualfy.adapters.jira import JiraOptions
from qualfy.adapters.sinks.jira_comment import JiraCommentSink
from qualfy.adapters.sources.jira_rovo import JiraRovoOptions, JiraRovoSource
from qualfy.core.errors import ContractError, SourceError
from qualfy.core.models import AutomationResult, CaseResult, CaseStatus, RunStatus, utcnow

CONTRACT = "spec: PROJ-10\ncases:\n  - id: TC-1\n    title: Login\n    steps: [Open, Submit]\n"

ISSUE = {
    "key": "PROJ-11",
    "fields": {
        "summary": "Tests for login",
        "status": {"name": "Ready for Automation"},
        "description": {
            "type": "doc", "version": 1,
            "content": [
                {"type": "paragraph", "content": [{"type": "text", "text": "Generated by Rovo"}]},
                {"type": "codeBlock", "attrs": {"language": "yaml"},
                 "content": [{"type": "text", "text": CONTRACT}]},
            ],
        },
    },
}

OPTS = dict(base_url="https://acme.atlassian.net", email="qa@acme.io", token="t")


def transport(requests: list[httpx.Request]) -> httpx.MockTransport:
    def handler(request: httpx.Request) -> httpx.Response:
        requests.append(request)
        path = request.url.path
        if path == "/rest/api/3/issue/PROJ-11":
            return httpx.Response(200, json=ISSUE)
        if path == "/rest/api/3/search/jql":
            return httpx.Response(200, json={"issues": [ISSUE]})
        if path == "/rest/api/3/issue/PROJ-11/comment":
            return httpx.Response(201, json={"id": "1"})
        return httpx.Response(404, text="not found")

    return httpx.MockTransport(handler)


async def test_fetch_and_normalize_from_adf():
    requests: list[httpx.Request] = []
    source = JiraRovoSource(JiraRovoOptions(**OPTS), transport=transport(requests))
    spec = await source.normalize(await source.fetch("PROJ-11"))
    assert spec.ref.key == "PROJ-11"
    assert spec.ref.url == "https://acme.atlassian.net/browse/PROJ-11"
    assert spec.title == "Tests for login"
    assert spec.generator == "rovo"
    assert spec.spec_ref and spec.spec_ref.key == "PROJ-10"
    assert requests[0].headers["authorization"].startswith("Basic ")


async def test_discover_uses_jql():
    requests: list[httpx.Request] = []
    source = JiraRovoSource(JiraRovoOptions(**OPTS, jql="project = PROJ"),
                            transport=transport(requests))
    items = await source.discover()
    assert [(i.ref.key, i.status) for i in items] == [("PROJ-11", "Ready for Automation")]
    assert json.loads(requests[0].content)["jql"] == "project = PROJ"


async def test_plain_text_description_fallback():
    source = JiraRovoSource(JiraRovoOptions(**OPTS), transport=transport([]))
    raw = {"key": "PROJ-12", "fields": {"summary": "s",
                                        "description": f"```yaml\n{CONTRACT}```"}}
    assert (await source.normalize(raw)).cases[0].id == "TC-1"


async def test_missing_contract():
    source = JiraRovoSource(JiraRovoOptions(**OPTS), transport=transport([]))
    with pytest.raises(ContractError):
        await source.normalize({"key": "X-1", "fields": {"description": None}})


async def test_http_errors_are_wrapped():
    source = JiraRovoSource(JiraRovoOptions(**OPTS), transport=transport([]))
    with pytest.raises(SourceError, match="404"):
        await source.fetch("NOPE-1")


async def test_comment_sink_posts_adf():
    requests: list[httpx.Request] = []
    source = JiraRovoSource(JiraRovoOptions(**OPTS), transport=transport(requests))
    spec = await source.normalize(ISSUE)
    sink = JiraCommentSink(JiraOptions(**OPTS), transport=transport(requests))
    result = AutomationResult(
        run_id="r1", spec_ref=spec.ref, spec_revision=spec.revision, status=RunStatus.SUCCESS,
        summary="All good", pr_url="https://git/pr/1", started_at=utcnow(), finished_at=utcnow(),
        cases=[CaseResult(case_id="TC-1", status=CaseStatus.AUTOMATED)],
    )
    await sink.publish(spec, result, sink.draft(spec, result))
    body = json.loads(requests[-1].content)["body"]
    assert body["type"] == "doc"
    flat = json.dumps(body)
    assert "SUCCESS" in flat and "TC-1 | Login" in flat and "https://git/pr/1" in flat
